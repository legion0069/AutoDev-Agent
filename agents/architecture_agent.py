"""
AutoDev Specialized Agent - ArchitectureAgent (v2.8)
====================================================
Specialized autonomous agent responsible for:
- System architecture decisions & design patterns
- Module boundaries & isolation layers
- Inter-package dependency management
- Public interface contracts & protocol specifications
"""

from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional

from core.collaboration.collaboration_models import AgentRole, MessageType, TaskAssignment
from .specialized_agent import SpecializedAgent

logger = logging.getLogger("autodev.agents.architecture")


class ArchitectureAgent(SpecializedAgent):
    """
    Lead System Architect agent ensuring clean boundaries, robust interface contracts,
    and modular decoupled architecture across the codebase.
    """

    def __init__(
        self,
        name: str = "ArchitectureAgent",
        llm_client: Optional[Any] = None,
        bus: Optional[Any] = None,
        workspace: Optional[Any] = None,
    ):
        super().__init__(
            name=name,
            role=AgentRole.ARCHITECTURE,
            llm_client=llm_client,
            bus=bus,
            workspace=workspace,
        )

    def define_architecture(
        self,
        project_name: str,
        requirements: List[str],
        patterns: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """Generate architectural specifications and layer boundaries."""
        spec = {
            "project_name": project_name,
            "patterns": patterns or ["Layered Architecture", "Dependency Inversion", "Event-Driven Bus"],
            "modules": {
                "core": "Domain models, orchestration, and business rules",
                "adapters": "Network, database, filesystem, and external integrations",
                "api": "Transport layer, REST/RPC endpoints, and serializers",
                "ui": "Presentation components, state management, and views",
            },
            "dependency_rules": [
                "UI depends on API and Models",
                "API depends on Core Domain Services",
                "Core Domain has zero dependencies on Infrastructure/Adapters",
            ],
        }
        return spec

    def validate_boundaries(self, modules: List[str], dependency_graph: Dict[str, List[str]]) -> Dict[str, Any]:
        """Verify that module import boundaries comply with architectural layering."""
        violations = []
        for mod, deps in dependency_graph.items():
            if mod == "core":
                for dep in deps:
                    if dep in ("ui", "api", "dashboard"):
                        violations.append(f"Inverted dependency: 'core' cannot import from '{dep}'")
        return {
            "valid": len(violations) == 0,
            "violations": violations,
        }

    def execute_task(
        self,
        task: TaskAssignment,
        context: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Execute architecture planning, interface definition, or boundary audits."""
        logger.info("ArchitectureAgent executing: %s", task.title)

        staged_files = {}
        if "interface" in task.title.lower() or "contract" in task.title.lower():
            if task.estimated_files:
                for fpath in task.estimated_files:
                    content = (
                        f"# Architecture Interface Contract: {task.title}\n"
                        f"# Generated by {self.name} (v2.8)\n\n"
                        f"from typing import Protocol, Any, Dict\n\n"
                        f"class I{task.title.replace(' ', '')}(Protocol):\n"
                        f"    def execute(self, payload: Dict[str, Any]) -> Any:\n"
                        f"        ...\n"
                    )
                    staged_files[fpath] = content

        # Broadcast architecture update notification to the bus
        if self.bus:
            self.send_message(
                receiver="*",
                message_type=MessageType.NOTIFICATION,
                payload={
                    "event": "architecture_updated",
                    "task_id": task.task_id,
                    "title": task.title,
                },
                task_id=task.task_id,
            )

        return {
            "agent": self.name,
            "role": self.role.value,
            "task_id": task.task_id,
            "action": "architectural_synthesis",
            "staged_files": staged_files,
            "summary": f"Completed architectural specification and interface alignment for '{task.title}'.",
        }
