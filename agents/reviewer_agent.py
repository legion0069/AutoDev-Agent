class ReviewValidationError(ValueError):
    """
    Raised when an LLM review response fails validation against the required schema.
    """
    pass


VALID_SEVERITIES = {"LOW", "MEDIUM", "HIGH", "CRITICAL"}


@dataclass
class Issue:
    """
    Represents an individual code quality, architectural, or security finding.
    """
    severity: str
    category: str
    file: str
    line: Optional[int]
    description: str
    recommendation: str

    def to_dict(self) -> Dict[str, Any]:
        """Converts issue to dictionary representation."""
        return asdict(self)


@dataclass
class ReviewResult:
    """
    Structured outcome of the AI code review pipeline.
    """
    success: bool
    summary: str
    overall_quality_score: int
    issues: List[Issue] = field(default_factory=list)
    strengths: List[str] = field(default_factory=list)
    recommendations: List[str] = field(default_factory=list)
    should_regenerate: bool = False
    explanation: str = ""

    def to_dict(self) -> Dict[str, Any]:
        """Converts review result to dictionary representation."""
        return {
            "success": self.success,
            "summary": self.summary,
            "overall_quality_score": self.overall_quality_score,
            "issues": [i.to_dict() for i in self.issues],
            "strengths": self.strengths,
            "recommendations": self.recommendations,
            "should_regenerate": self.should_regenerate,
            "explanation": self.explanation,
        }


