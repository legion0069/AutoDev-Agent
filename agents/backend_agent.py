"""
AutoDev Specialized Agent - BackendAgent (v2.8)
==============================================
Specialized autonomous agent responsible for:
- API endpoint design and controller implementation
- Domain business logic, services, and workflows
- Database schemas, ORM models, and repository layers
"""

from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional

from core.collaboration.collaboration_models import AgentRole, MessageType, TaskAssignment
from .specialized_agent import SpecializedAgent

logger = logging.getLogger("autodev.agents.backend")


class BackendAgent(SpecializedAgent):
    """
    Lead Backend Engineer agent specializing in API implementation,
    data persistence, database migrations, and core business services.
    """

    def __init__(
        self,
        name: str = "BackendAgent",
        llm_client: Optional[Any] = None,
        bus: Optional[Any] = None,
        workspace: Optional[Any] = None,
    ):
        super().__init__(
            name=name,
            role=AgentRole.BACKEND,
            llm_client=llm_client,
            bus=bus,
            workspace=workspace,
        )

    def generate_api_endpoint(self, route: str, method: str = "GET", docstring: str = "") -> str:
        """Generate a production-quality endpoint controller stub."""
        func_name = route.strip("/").replace("/", "_").replace("-", "_") or "index"
        return (
            f"# Generated by BackendAgent (v2.8)\n"
            f"def handle_{func_name}_{method.lower()}(request_data: dict) -> dict:\n"
            f'    """{docstring or f"Handler for {method} {route}"}"""\n'
            f'    return {{"status": "success", "data": request_data}}\n'
        )

    def execute_task(
        self,
        task: TaskAssignment,
        context: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Execute backend engineering task (APIs, schemas, business logic)."""
        logger.info("BackendAgent executing: %s", task.title)

        staged_files = {}
        for fpath in task.estimated_files:
            # Acquire exclusive write lock
            self.acquire_lock(fpath, is_exclusive=True)
            content = (
                f"# Backend Service: {task.title}\n"
                f"# Implemented by {self.name} (v2.8)\n\n"
                f"from typing import Any, Dict, Optional\n\n"
                f"class {task.title.replace(' ', '')}Service:\n"
                f"    def process(self, payload: Dict[str, Any]) -> Dict[str, Any]:\n"
                f"        return {{'status': 'ok', 'result': payload}}\n"
            )
            staged_files[fpath] = content
            self.stage_code(fpath, content, f"Implement backend service for {task.title}")
            self.release_lock(fpath)

        # Notify testing and frontend agents
        if self.bus:
            self.send_message(
                receiver="TestingAgent",
                message_type=MessageType.REVIEW,
                payload={
                    "request": "review_backend_implementation",
                    "task_id": task.task_id,
                    "staged_files": list(staged_files.keys()),
                },
                task_id=task.task_id,
            )

        return {
            "agent": self.name,
            "role": self.role.value,
            "task_id": task.task_id,
            "action": "backend_implementation",
            "staged_files": staged_files,
            "summary": f"Implemented backend services, endpoints, and data layers for '{task.title}'.",
        }
