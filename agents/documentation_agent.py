"""
AutoDev Specialized Agent - DocumentationAgent (v2.8)
====================================================
Specialized autonomous agent responsible for:
- README files, quickstart guides, and operational runbooks
- Interactive OpenAPI / Swagger and module docstring specifications
- Architectural decision records (ADRs) and workflow documentation
"""

from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional

from core.collaboration.collaboration_models import AgentRole, MessageType, TaskAssignment
from .specialized_agent import SpecializedAgent

logger = logging.getLogger("autodev.agents.documentation")


class DocumentationAgent(SpecializedAgent):
    """
    Lead Technical Writer & Documentation Engineer agent ensuring complete,
    lucid, and up-to-date documentation across all packages and endpoints.
    """

    def __init__(
        self,
        name: str = "DocumentationAgent",
        llm_client: Optional[Any] = None,
        bus: Optional[Any] = None,
        workspace: Optional[Any] = None,
    ):
        super().__init__(
            name=name,
            role=AgentRole.DOCUMENTATION,
            llm_client=llm_client,
            bus=bus,
            workspace=workspace,
        )

    def generate_api_docs(self, endpoints: List[Dict[str, Any]]) -> str:
        """Generate markdown documentation for API endpoints."""
        doc = ["# API Reference\n"]
        for ep in endpoints:
            doc.append(f"### `{ep.get('method', 'GET')} {ep.get('path', '/')}`")
            doc.append(f"{ep.get('description', 'Endpoint description')}\n")
        return "\n".join(doc)

    def execute_task(
        self,
        task: TaskAssignment,
        context: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Execute documentation synthesis or verification."""
        logger.info("DocumentationAgent executing: %s", task.title)

        staged_files = {}
        for fpath in task.estimated_files:
            self.acquire_lock(fpath, is_exclusive=True)
            content = (
                f"# Documentation: {task.title}\n\n"
                f"Generated by {self.name} (AutoDev v2.8 Multi-Agent Framework).\n\n"
                f"## Overview\n"
                f"{task.description or 'Technical reference and architecture documentation.'}\n"
            )
            staged_files[fpath] = content
            self.stage_code(fpath, content, f"Document {task.title}")
            self.release_lock(fpath)

        return {
            "agent": self.name,
            "role": self.role.value,
            "task_id": task.task_id,
            "action": "documentation_synthesis",
            "staged_files": staged_files,
            "summary": f"Penned documentation, guides, and API specs for '{task.title}'.",
        }
