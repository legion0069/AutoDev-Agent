"""
coder_agent.py - Coder Agent for AutoDev

Responsible for executing a single atomic engineering task by constructing
an engineering prompt, querying the configured BaseLLM provider, and validating
the resulting structured JSON code generation payload into a GeneratedResult.
"""

from __future__ import annotations

import json
import logging
import re
import sys
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

# Ensure project root is available on sys.path for direct execution
