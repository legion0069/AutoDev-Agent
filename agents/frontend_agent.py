"""
AutoDev Specialized Agent - FrontendAgent (v2.8)
===============================================
Specialized autonomous agent responsible for:
- User interface (UI) components and pages
- Client-side state management and data stores
- Visual aesthetics, layouts, and responsive design
"""

from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional

from core.collaboration.collaboration_models import AgentRole, MessageType, TaskAssignment
from .specialized_agent import SpecializedAgent

logger = logging.getLogger("autodev.agents.frontend")


class FrontendAgent(SpecializedAgent):
    """
    Lead Frontend Engineer agent specializing in client UI/UX architectures,
    component lifecycles, and responsive presentation layers.
    """

    def __init__(
        self,
        name: str = "FrontendAgent",
        llm_client: Optional[Any] = None,
        bus: Optional[Any] = None,
        workspace: Optional[Any] = None,
    ):
        super().__init__(
            name=name,
            role=AgentRole.FRONTEND,
            llm_client=llm_client,
            bus=bus,
            workspace=workspace,
        )

    def generate_ui_component(self, component_name: str, props: List[str]) -> str:
        """Generate a clean component template."""
        props_str = ", ".join(props)
        return (
            f"// Component: {component_name} (Generated by FrontendAgent v2.8)\n"
            f"export function {component_name}({{ {props_str} }}) {{\n"
            f"  return (\n"
            f'    <div className="{component_name.lower()}-container">\n'
            f"      <h2>{component_name}</h2>\n"
            f"    </div>\n"
            f"  );\n"
            f"}}\n"
        )

    def execute_task(
        self,
        task: TaskAssignment,
        context: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Execute frontend UI, state, or component tasks."""
        logger.info("FrontendAgent executing: %s", task.title)

        staged_files = {}
        for fpath in task.estimated_files:
            self.acquire_lock(fpath, is_exclusive=True)
            content = (
                f"// Frontend Component: {task.title}\n"
                f"// Authored by {self.name} (v2.8)\n\n"
                f"export const {task.title.replace(' ', '')}View = () => {{\n"
                f"  return <div>Rendered {task.title}</div>;\n"
                f"}};\n"
            )
            staged_files[fpath] = content
            self.stage_code(fpath, content, f"Implement UI view for {task.title}")
            self.release_lock(fpath)

        if self.bus:
            self.send_message(
                receiver="BackendAgent",
                message_type=MessageType.QUESTION,
                payload={
                    "query": "verify_api_schema_compatibility",
                    "task_id": task.task_id,
                },
                task_id=task.task_id,
            )

        return {
            "agent": self.name,
            "role": self.role.value,
            "task_id": task.task_id,
            "action": "frontend_implementation",
            "staged_files": staged_files,
            "summary": f"Built UI views and client state components for '{task.title}'.",
        }
