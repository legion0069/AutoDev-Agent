# 4. Git Commit Flow Tests
# =============================================================================

def test_git_commit_created_for_successful_tasks(multi_day_project_env):
    """Verifies that GitAgent commits changes for each successfully completed task."""
    git_commits = []

    class TrackingGitAgent(GitAgent):
        def commit(self, message=None, task=None, review_result=None, files_to_stage=None, allow_empty=False):
            commit_hash = f"abc{len(git_commits) + 1:04d}"
            git_commits.append(commit_hash)
            return CommitResult(
                success=True,
                commit_hash=commit_hash,
                commit_message=f"feat: completed {task.id if task else 'task'}",
                branch="main",
            )

    orch = Orchestrator(
        project_root=multi_day_project_env["workspace"],
        plan_path=multi_day_project_env["plan_path"],
        state_path=multi_day_project_env["state_path"],
        tasks_path=multi_day_project_env["tasks_path"],
        log_dir=multi_day_project_env["logs_dir"],
        git_agent=TrackingGitAgent(project_root=multi_day_project_env["workspace"], auto_init=False),
    )

    summary = orch.run()
    assert len(summary.commits_created) > 0
    assert len(summary.commits_created) == len(summary.tasks_completed)


