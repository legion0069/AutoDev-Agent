# 3. Retry Flow Invocation Tests
# =============================================================================

def test_retry_flow_invoked_on_defect_or_test_failure(multi_day_project_env):
    """Verifies that low quality scores or test failures invoke the RetryEngine."""
    call_counts = {"review": 0, "retry": 0}

    class FlakyReviewer(ReviewerAgent):
        def review(self, context, generated_result, test_result=None):
            call_counts["review"] += 1
            # First task triggers retry via should_regenerate=True
            if call_counts["review"] == 1:
                return ReviewResult(
                    success=True,
                    summary="Needs work",
                    overall_quality_score=60,
                    should_regenerate=True,
                )
            return ReviewResult(
                success=True,
                summary="Good code",
                overall_quality_score=92,
                should_regenerate=False,
            )

    class MockRetryEngine(RetryEngine):
        def execute(self, context, task, max_attempts=None, minimum_quality_score=None):
            call_counts["retry"] += 1
            return RetryResult(
                success=True,
                attempts=2,
                max_attempts=3,
                final_generated_result=GeneratedResult(
                    summary="Regenerated",
                    files=[GeneratedFile(path="src/fixed.py", content="# fixed\n")],
                    explanation="Self-healed",
                ),
                final_test_result=TestResult(
                    success=True,
                    total_tests=1,
                    passed=1,
                    failed=0,
                    skipped=0,
                    duration=0.1,
                    stdout="1 passed in 0.10s",
                    stderr="",
                    exit_code=0,
                    command="pytest",
                    message="All tests passed.",
                ),
                final_review_result=ReviewResult(success=True, summary="Clean", overall_quality_score=90, should_regenerate=False),
            )

    orch = Orchestrator(
        project_root=multi_day_project_env["workspace"],
        plan_path=multi_day_project_env["plan_path"],
        state_path=multi_day_project_env["state_path"],
        tasks_path=multi_day_project_env["tasks_path"],
        log_dir=multi_day_project_env["logs_dir"],
        reviewer_agent=FlakyReviewer(),
        retry_engine=MockRetryEngine(),
    )

    summary = orch.run()
    assert call_counts["retry"] >= 1
    assert summary.overall_success is True


