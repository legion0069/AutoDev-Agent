# 5. Partial Failures & Loop Continuation Tests
# =============================================================================

def test_partial_task_failure_continues_remaining_tasks(multi_day_project_env):
    """Verifies that if one task fails, remaining tasks continue processing."""
    class SelectiveFailingCoder(CoderAgent):
        def execute(self, context, task):
            # TASK01 throws exception
            if task.id == "DAY1-TASK01":
                raise RuntimeError("LLM synthesis failure on Task 1")
            return GeneratedResult(
                summary="Success",
                files=[GeneratedFile(path="src/ok.py", content="# ok\n")],
                explanation="Done",
            )

    orch = Orchestrator(
        project_root=multi_day_project_env["workspace"],
        plan_path=multi_day_project_env["plan_path"],
        state_path=multi_day_project_env["state_path"],
        tasks_path=multi_day_project_env["tasks_path"],
        log_dir=multi_day_project_env["logs_dir"],
        coder_agent=SelectiveFailingCoder(),
    )

    summary = orch.run()

    # TASK01 should be in tasks_failed, while others succeed
    assert "DAY1-TASK01" in summary.tasks_failed
    assert len(summary.tasks_completed) >= 1
    assert summary.overall_success is False
    assert summary.next_day == 1  # Day does not advance because of failure


